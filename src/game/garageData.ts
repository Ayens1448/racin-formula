export function calculateEffectiveSpecs(baseSpecs: CarSpecs, upgrades: CarUpgradeLevels): CarSpecs {
  return {
    topSpeed: baseSpecs.topSpeed + (upgrades.engine - 1) * 5,
    acceleration: baseSpecs.acceleration + (upgrades.hybridMgu - 1) * 0.16,
    corneringGrip: baseSpecs.corneringGrip + (upgrades.aeroDownforce - 1) * 0.16,
    brakingPower: baseSpecs.brakingPower + (upgrades.brakes - 1) * 0.42,
    drsBoost: baseSpecs.drsBoost + (upgrades.drsWing - 1) * 3.5,
    aeroStability: baseSpecs.aeroStability + (upgrades.chassis - 1) * 0.18,
  };
}
